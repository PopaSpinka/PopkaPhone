// НаомиФон — поверхность программы по контуру окна стола: скруглённые углы без слоя и маски. Узел Qt Wayland —
// прямоугольник с текстурой окна программы; если он задевает угол контура, рисует его дочерний узел — та же текстура
// треугольниками по контуру ∩ видимая часть, а сам узел Qt Wayland — пустой прямоугольник. Угла не задел — как есть.
// Край можно сгладить: кайма в пиксель с убывающей видимостью (шейдеры shaders/outline.*).
// Так режут углы окна Android (android_surface.h) и страница браузера (web_surface.h): слой с маской на каждый кадр
// страницы стоил видеочипу четверть его загрузки на ролике (docs/AUDIT.md, этап 1).
#pragma once

#include <QRectF>

class QSGSimpleTextureNode;

// node — узел поверхности (после QWaylandQuickItem::updatePaintNode); outline — контур окна в единицах элемента,
// corner — радиус его углов («непрерывные», как DeskStyle.outline), drawn — видимая часть элемента; pixel — пиксель
// кадра в единицах элемента: больше нуля — край сглажен каймой в пиксель (без неё кривая угла — ступеньками).
// solid — текстура без своей прозрачности (кадр wl_shm XRGB, у которого в старшем байте что угодно, web_surface.h):
// рисует всегда дочерний узел, шейдером shaders/solid.frag — прозрачность пикселя берётся за 1
void cutToOutline(QSGSimpleTextureNode *node, const QRectF &outline, qreal corner, const QRectF &drawn, qreal pixel = 0,
                  bool solid = false);
